/**
 * Twelve 16x16 pixel icons for a game or app (heart, star, coin, key...), one per frame and named by markers, so a
 * sprite sheet export lays them out on a grid with a name for each.
 */
export function makeUiIcons(): Doc {
  const doc = emptyOf(newDoc({ name: 'UI icon set', width: 256, height: 256, fps: 4, length: ICONS.length, background: null }));
  const names: Record<string, string> = { k: 'Outline', w: 'Shine', y: 'Gold', o: 'Gold shade', r: 'Red', R: 'Red shade', b: 'Blue', B: 'Blue shade', m: 'Green', M: 'Green shade', g: 'Steel', G: 'Steel shade', n: 'Wood' };
  swatchesFrom(doc, Object.entries(PALETTE).map(([k, c]) => [names[k], c]));
  const layer = addPixelLayer(doc, 'Icons', 16);
  ICONS.forEach((icon, i) => {
    hold(layer, pixelDrawing(doc, icon.rows, PALETTE).id, i);
    addMarker(doc, icon.name, i);
  });
  return doc;
}

