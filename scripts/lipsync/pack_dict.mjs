// Packs the pronunciation list for lip sync (see make_dict.py) into src/lipsync/dict-data.ts.
//   node scripts/lipsync/pack_dict.mjs <full.json> [--stats]
// Keeps only the words the spelling guide (with the endings rules) gets wrong, so the data stays small. Rerun it
// whenever the guide in src/lipsync/text.ts or the rules in src/lipsync/words.ts change: test/lipsync/dict.test.ts fails when the data is out of date.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const args = process.argv.slice(2);
const full = JSON.parse(readFileSync(resolve(args[0]), 'utf8'));
const tmp = mkdtempSync(join(tmpdir(), 'lippack-'));
await build({ entryPoints: [resolve('src/lipsync/words.ts')], bundle: true, format: 'esm', platform: 'node', outfile: join(tmp, 't.mjs'), logLevel: 'error' });
const { pronounceCodes, packDictionary } = await import(pathToFileURL(join(tmp, 't.mjs')).href);

// Collapse adjacent matching consonants, as the runtime does, then keep a word only if the guide gets it wrong.
const squash = (c) => [...c].reduce((o, ch) => (o.endsWith(ch) && !'AEOU'.includes(ch) ? o : o + ch), '');
const words = Object.keys(full).sort((a, b) => a.length - b.length || (a < b ? -1 : 1));
const kept = new Map();
for (const w of words) {
  const want = squash(full[w]);
  if (pronounceCodes(w, kept) !== want) kept.set(w, want);
}
const data = packDictionary(kept);
const header = `// Generated by scripts/lipsync/pack_dict.mjs from scripts/lipsync/make_dict.py. Do not edit.
// Pronunciations: the CMU Pronouncing Dictionary as compiled into Flite (BSD-style licence, Carnegie Mellon University),
// reduced to the ten mouths (the sounds themselves are not kept). Words: the wamerican list (public domain / SCOWL).
// CMU Pronouncing Dictionary: Copyright (C) 1993-2015 Carnegie Mellon University. All rights reserved. Redistribution and
// use in source and binary forms, with or without modification, are permitted provided the copyright notice and the
// disclaimer of the CMU licence are kept; the dictionary is provided "as is" with no warranty. See src/lipsync/dict.ts.
`;
writeFileSync(resolve('src/lipsync/dict-data.ts'), `${header}export default '${data}';\n`);
console.log(`${words.length} words, ${kept.size} kept (${((kept.size / words.length) * 100).toFixed(0)}%), ${data.length} bytes`);
